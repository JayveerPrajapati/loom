// Package runbook renders a workflow as a human-readable Markdown document.
package runbook

import (
	"fmt"
	"sort"
	"strings"

	"loom/internal/graph"
)

func Render(wf *graph.Workflow) string {
	if wf == nil {
		return ""
	}
	var b strings.Builder
	name := strings.TrimSpace(wf.Name)
	if name == "" {
		name = wf.ID
	}
	fmt.Fprintf(&b, "# %s\n\n", escape(name))
	fmt.Fprintf(&b, "Generated by Loom from workflow `%s` (version %d).\n\n", escape(wf.ID), wf.Version)

	b.WriteString("## Run it\n\n")
	b.WriteString("```sh\n")
	fmt.Fprintf(&b, "loom import %s.flow.json\n", slug(wf.ID))
	fmt.Fprintf(&b, "loom run %s.flow.json --input '{}'\n", slug(wf.ID))
	b.WriteString("```\n\n")
	fmt.Fprintf(&b, "Or start it over HTTP:\n\n```sh\ncurl -X POST http://localhost:5678/api/workflows/%s/runs \\\n  -H 'Content-Type: application/json' -d '{\"input\":{}}'\n```\n\n", escape(wf.ID))

	b.WriteString("## Triggers\n\n")
	triggers := 0
	for _, node := range wf.Nodes {
		if !strings.HasPrefix(node.Type, "trigger.") {
			continue
		}
		triggers++
		detail := node.Type
		switch {
		case node.Config["path"] != nil:
			detail = fmt.Sprintf("webhook `%v`", node.Config["path"])
		case node.Config["schedule"] != nil:
			detail = fmt.Sprintf("schedule `%v`", node.Config["schedule"])
		}
		fmt.Fprintf(&b, "- **%s** — %s\n", escape(displayName(node)), detail)
	}
	if triggers == 0 {
		b.WriteString("No trigger node; start this workflow manually.\n")
	}
	b.WriteString("\n")

	creds := map[string]bool{}
	for _, node := range wf.Nodes {
		for key := range node.Credentials {
			creds[key] = true
		}
	}
	if len(creds) > 0 {
		keys := make([]string, 0, len(creds))
		for key := range creds {
			keys = append(keys, key)
		}
		sort.Strings(keys)
		b.WriteString("## Credentials\n\n")
		for _, key := range keys {
			fmt.Fprintf(&b, "- `%s`\n", escape(key))
		}
		b.WriteString("\n")
	}

	b.WriteString("## Nodes\n\n")
	b.WriteString("| # | Node | Type | Version |\n|---:|---|---|---:|\n")
	for index, node := range wf.Nodes {
		fmt.Fprintf(&b, "| %d | %s | `%s` | %d |\n", index+1, escape(displayName(node)), escape(node.Type), node.TypeVersion)
	}
	b.WriteString("\n")

	b.WriteString("## Connections\n\n")
	if len(wf.Edges) == 0 {
		b.WriteString("No connections.\n\n")
	} else {
		for _, edge := range wf.Edges {
			fmt.Fprintf(&b, "- `%s.%s` → `%s.%s`\n", escape(edge.From.Node), escape(edge.From.Port), escape(edge.To.Node), escape(edge.To.Port))
		}
		b.WriteString("\n")
	}

	b.WriteString("## Inspect and replay\n\n")
	b.WriteString("```sh\n")
	b.WriteString("loom runs --data ./data\n")
	fmt.Fprintf(&b, "loom replay --data ./data <run-id>\n")
	fmt.Fprintf(&b, "loom replay --data ./data --step <node-id> <run-id>\n")
	b.WriteString("```\n")
	return b.String()
}

func displayName(node graph.Node) string {
	if strings.TrimSpace(node.Name) != "" {
		return node.Name
	}
	return node.ID
}

func escape(value string) string {
	return strings.ReplaceAll(value, "`", "'")
}

func slug(value string) string {
	value = strings.ToLower(strings.TrimSpace(value))
	value = strings.Map(func(r rune) rune {
		if r >= 'a' && r <= 'z' || r >= '0' && r <= '9' || r == '-' || r == '_' {
			return r
		}
		return '-'
	}, value)
	if value == "" {
		return "workflow"
	}
	return value
}
